#!/bin/zsh
# Create "GarminxSleep.app" in /Applications (macOS), or in ~/Applications if
# /Applications isn't writable. Set GARMINXSLEEP_APP_DIR to choose the folder.
#
#   scripts/install_app.sh               install (or update)
#   scripts/install_app.sh --uninstall
#
# Opening the app starts the dashboard server, shows it in its own window, and
# stops the server when the window closes. Needs the [app] extra installed:
#   .venv/bin/pip install -e ".[app]"
#
#   GARMINXSLEEP_DATA_DIR  data folder (default: <project>/private)
#   GARMINXSLEEP_PYTHON    Python with the project installed
#                          (default: <project>/.venv/bin/python)
set -euo pipefail

name=GarminxSleep
if [[ -n ${GARMINXSLEEP_APP_DIR:-} ]]; then
  app_dir=$GARMINXSLEEP_APP_DIR
elif [[ -w /Applications ]]; then
  app_dir=/Applications
else
  app_dir=$HOME/Applications
fi
app=$app_dir/$name.app
project=${0:A:h:h}
# Earlier versions installed "Sleep Dashboard.app" here; remove it too.
old_app=$HOME/Applications/"Sleep Dashboard.app"

if [[ ${1:-} == --uninstall ]]; then
  rm -rf "$app" "$old_app"
  print "Removed $app"
  exit 0
fi

python=${GARMINXSLEEP_PYTHON:-$project/.venv/bin/python}
data_dir=${GARMINXSLEEP_DATA_DIR:-$project/private}
if [[ ! -x $python ]]; then
  print -u2 "No Python found at $python. Create the venv first (see README) or set GARMINXSLEEP_PYTHON."
  exit 1
fi
if ! "$python" -c "import webview" 2>/dev/null; then
  print -u2 "pywebview is missing. Install the app extra first:  $python -m pip install -e \"${project}[app]\""
  exit 1
fi

rm -rf "$app" "$old_app"
mkdir -p "$app/Contents/MacOS" "$app/Contents/Resources"

# App icon: every size macOS asks for, made from the 1024 px PNG.
iconset=$(mktemp -d)/GarminxSleep.iconset
mkdir -p "$iconset"
for size in 16 32 128 256 512; do
  sips -z $size $size "$project/dashboard/assets/app_icon.png" --out "$iconset/icon_${size}x${size}.png" >/dev/null
  sips -z $((size * 2)) $((size * 2)) "$project/dashboard/assets/app_icon.png" --out "$iconset/icon_${size}x${size}@2x.png" >/dev/null
done
iconutil -c icns "$iconset" -o "$app/Contents/Resources/GarminxSleep.icns"
rm -rf "${iconset:h}"
cat >"$app/Contents/Info.plist" <<EOF
<?xml version="1.0" encoding="UTF-8"?>
<!DOCTYPE plist PUBLIC "-//Apple//DTD PLIST 1.0//EN" "http://www.apple.com/DTDs/PropertyList-1.0.dtd">
<plist version="1.0">
<dict>
  <key>CFBundleName</key><string>$name</string>
  <key>CFBundleDisplayName</key><string>$name</string>
  <key>CFBundleIdentifier</key><string>com.garminxsleep.dashboard</string>
  <key>CFBundleExecutable</key><string>launch</string>
  <key>CFBundleIconFile</key><string>GarminxSleep</string>
  <key>CFBundlePackageType</key><string>APPL</string>
  <key>CFBundleVersion</key><string>1</string>
  <key>NSHighResolutionCapable</key><true/>
</dict>
</plist>
EOF
cat >"$app/Contents/MacOS/launch" <<EOF
#!/bin/zsh
# Generated by scripts/install_app.sh; rerun it to update.
export GARMINXSLEEP_DATA_DIR="$data_dir"
cd "$project"
exec "$python" -m dashboard.desktop >>"$data_dir/app.log" 2>&1
EOF
chmod +x "$app/Contents/MacOS/launch"
# Make Finder and the Dock pick up the new icon instead of a cached one.
touch "$app"
print "Installed $app (data: $data_dir). Open it from Applications, Launchpad or Spotlight; drag it to the Dock to keep it there."
